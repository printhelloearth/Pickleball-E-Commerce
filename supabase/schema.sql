create policy "Staff can read staff profiles"
  on public.staff_profiles for select to authenticated
  using (public.is_store_staff());
create policy "Owners manage staff profiles"
  on public.staff_profiles for all to authenticated
  using (public.has_store_role(array['owner']::public.staff_role[]))
  with check (public.has_store_role(array['owner']::public.staff_role[]));

create policy "Active products are public"
  on public.products for select to anon, authenticated using (active);
create policy "Staff can read all products"
  on public.products for select to authenticated using (public.has_store_permission('products'));
create policy "Managers manage products"
  on public.products for all to authenticated
  using (public.has_store_permission('products'))
  with check (public.has_store_permission('products'));

create policy "Active variants are public"
  on public.product_variants for select to anon, authenticated
  using (active and exists (
    select 1 from public.products p where p.id = product_id and p.active
  ));
create policy "Staff can read all variants"
  on public.product_variants for select to authenticated
  using (public.has_store_permission('products'));
create policy "Managers manage variants"
  on public.product_variants for all to authenticated
  using (public.has_store_permission('products'))
  with check (public.has_store_permission('products'));

create policy "Public can read stock for active variants"
  on public.inventory for select to anon, authenticated
  using (exists (
    select 1 from public.product_variants v
    join public.products p on p.id = v.product_id
    where v.id = variant_id and v.active and p.active
  ));
create policy "Staff manage inventory"
  on public.inventory for all to authenticated
  using (public.has_store_permission('inventory'))
  with check (public.has_store_permission('inventory'));

create policy "Staff read customers"
  on public.customers for select to authenticated using (public.has_store_permission('orders'));
create policy "Customers read own profile"
  on public.customers for select to authenticated using (user_id = (select auth.uid()));
create policy "Managers manage customers"
  on public.customers for all to authenticated
  using (public.has_store_permission('orders'))
  with check (public.has_store_permission('orders'));

create policy "Staff read orders"
  on public.orders for select to authenticated using (public.has_store_permission('orders'));
create policy "Managers manage orders"
  on public.orders for all to authenticated
  using (public.has_store_permission('orders'))
  with check (public.has_store_permission('orders'));
create policy "Customers read own orders"
  on public.orders for select to authenticated
  using (customer_id in (
    select c.id from public.customers c where c.user_id = (select auth.uid())
  ));
create policy "Staff read order items"
  on public.order_items for select to authenticated using (public.has_store_permission('orders'));
create policy "Managers manage order items"
  on public.order_items for all to authenticated
  using (public.has_store_permission('orders'))
  with check (public.has_store_permission('orders'));
create policy "Customers read own order items"
  on public.order_items for select to authenticated
  using (order_id in (
    select o.id from public.orders o
    where o.customer_id in (
      select c.id from public.customers c where c.user_id = (select auth.uid())
    )
  ));
create policy "Staff read inventory history"
  on public.inventory_movements for select to authenticated
  using (public.has_store_permission('inventory'));
create policy "Managers record inventory history"
  on public.inventory_movements for insert to authenticated
  with check (public.has_store_permission('inventory'));

create policy "Active discount codes are publicly readable"
  on public.discounts for select to anon, authenticated using (active);
create policy "Staff manage discounts"
  on public.discounts for all to authenticated
  using (public.has_store_permission('orders'))
  with check (public.has_store_permission('orders'));
create policy "Staff read payment records"
  on public.payments for select to authenticated using (public.has_store_permission('orders'));

grant select on public.products, public.product_variants, public.inventory, public.discounts
  to anon, authenticated;
grant select, insert, update, delete on
  public.staff_profiles, public.products, public.product_variants, public.inventory,
  public.customers, public.orders, public.order_items, public.inventory_movements,
  public.discounts, public.payments to authenticated;

