-- Run in the Supabase SQL editor before connecting a production frontend.
-- Staff accounts must be created through Supabase Auth by the owner; never expose
-- service-role credentials in a browser application.

create type public.staff_role as enum ('owner', 'manager', 'cashier');
create type public.order_status as enum (
  'pending', 'processing', 'ready_for_pickup', 'shipped', 'completed', 'cancelled'
);
create type public.sales_channel as enum ('online', 'in_store');

create table public.staff_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.staff_role not null default 'cashier',
  permissions text[] not null default array['pos']::text[]
    check (permissions <@ array['overview', 'products', 'inventory', 'orders', 'pos']::text[]),
  created_at timestamptz not null default now()
);

create table public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  description text not null default '',
  category text not null,
  price numeric(10, 2) not null check (price >= 0),
  sku text unique,
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_variants (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  name text not null,
  sku text unique,
  price_override numeric(10, 2) check (price_override >= 0),
  attributes jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (product_id, name)
);

create table public.inventory (
  variant_id uuid primary key references public.product_variants(id) on delete cascade,
  quantity integer not null default 0 check (quantity >= 0),
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  updated_at timestamptz not null default now()
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  email text not null,
  phone text,
  created_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  channel public.sales_channel not null default 'online',
  status public.order_status not null default 'pending',
  fulfillment text not null default 'shipping'
    check (fulfillment in ('shipping', 'pickup')),
  subtotal numeric(10, 2) not null check (subtotal >= 0),
  tax numeric(10, 2) not null default 0 check (tax >= 0),
  shipping numeric(10, 2) not null default 0 check (shipping >= 0),
  total numeric(10, 2) not null check (total >= 0),
  shipping_address jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  variant_id uuid references public.product_variants(id) on delete set null,
  product_name text not null,
  variant_name text not null default '',
  sku text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  line_total numeric(10, 2) not null check (line_total >= 0)
);

create table public.inventory_movements (
  id uuid primary key default gen_random_uuid(),
  variant_id uuid not null references public.product_variants(id) on delete restrict,
  quantity_delta integer not null check (quantity_delta <> 0),
  reason text not null check (reason in (
    'restock', 'sale', 'return', 'correction', 'reservation', 'release'
  )),
  order_id uuid references public.orders(id) on delete set null,
  note text,
  actor_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.discounts (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  percent_off numeric(5, 2) check (percent_off > 0 and percent_off <= 100),
  amount_off numeric(10, 2) check (amount_off > 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (num_nonnulls(percent_off, amount_off) = 1)
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  provider text not null,
  provider_reference text,
  amount numeric(10, 2) not null check (amount >= 0),
  status text not null check (status in (
    'requires_payment', 'authorized', 'paid', 'refunded', 'failed'
  )),
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();
create trigger inventory_set_updated_at
  before update on public.inventory
  for each row execute function public.set_updated_at();
create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

create index products_category_active_idx on public.products(category, active);
create index product_variants_product_active_idx on public.product_variants(product_id, active);
create index orders_created_at_idx on public.orders(created_at desc);
create index order_items_order_id_idx on public.order_items(order_id);
create index inventory_movements_variant_created_idx
  on public.inventory_movements(variant_id, created_at desc);

create or replace function public.is_store_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff_profiles
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.has_store_role(required_roles public.staff_role[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff_profiles
    where user_id = (select auth.uid())
      and role = any(required_roles)
  );
$$;

create or replace function public.has_store_permission(required_permission text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff_profiles
    where user_id = (select auth.uid())
      and (
        role = 'owner'
        or permissions @> array[required_permission]::text[]
      )
  );
$$;

